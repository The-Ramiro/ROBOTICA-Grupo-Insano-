def lspb_clase(tk, qi=0.0, qf=2.0, tf=3.0, a=1.0, tc=1.0):
    # perfil de la clase W09-S01/S02 (qi = 0 -> qf = 2 rad, tf = 3 s, q̈c = 1 rad/s², tc = 1 s)
    if tk <= tc:
        return qi + 0.5 * a * tk**2, a
    if tk <= tf - tc:
        return qi + a * tc * (tk - tc / 2), 0.0
    return qf - 0.5 * a * (tf - tk)**2, -a

