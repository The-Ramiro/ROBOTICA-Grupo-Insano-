fig = plt.figure(figsize=(7, 5.5))
ax = fig.add_subplot(projection="3d")
colores = {"frente-arriba": "tab:blue", "frente-abajo": "tab:green", "espaldas-arriba": "tab:red", "espaldas-abajo": "tab:purple"}
